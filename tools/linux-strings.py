def main():
    out_dir = os.path.join(ROOT, "LinuxApp", "Resources", "Strings")
    os.makedirs(out_dir, exist_ok=True)
    for code, values in T.items():
        assert len(values) == len(KEYS), (code, len(values))
        mac = json.load(open(os.path.join(ROOT, "MacApp", "Resources", "Strings", f"{code}.json"), encoding="utf-8"))
        strings = {k: mac[src] for k, src in FROM_MAC.items() if src in mac}
        strings.update(dict(zip(KEYS, values)))
        strings["target.browser.chromium.name"] = "Chromium"  # a name, the same in every language
        for disk_id, (name, desc) in zip(DISK_IDS, DISK[code]):
            strings[f"space.{disk_id}.name"] = name
            strings[f"space.{disk_id}.desc"] = desc
        if code in GAPS:
            strings.setdefault("target.linux.trash.desc", GAPS[code][0])
            strings.setdefault("target.dev.bun.desc", GAPS[code][1])
        with open(os.path.join(out_dir, f"{code}.json"), "w", encoding="utf-8") as f:
            json.dump(strings, f, ensure_ascii=False, indent=2)
            f.write("\n")
    print(f"wrote {len(T)} languages, {len(KEYS) + len(FROM_MAC)} keys each")

if __name__ == "__main__":
    main()
